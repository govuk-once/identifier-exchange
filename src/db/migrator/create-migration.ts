/**
 * Scaffolds a new migration and registers it in migrations/index.ts.
 *
 *   pnpm migration:create add exchange status
 *   → src/db/migrations/20261111093000_add_exchange_status.ts
 *
 * Runs directly under Node's type stripping, so it imports only packages
 * and node: built-ins (a relative import would need a `.ts` extension there).
 */
import { Logger } from '@aws-lambda-powertools/logger';
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const MIGRATIONS_DIR = path.join(import.meta.dirname, '..', 'migrations');

const MIGRATION_FILE = /^(\d{14})_[a-z0-9]+(?:_[a-z0-9]+)*\.ts$/;

/** `"Add exchange status!"` → `"add_exchange_status"`. */
export const toSnakeCase = (description: string): string =>
  description
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');

const formatTimestamp = (date: Date): string => date.toISOString().replace(/\D/g, '').slice(0, 14);

const parseTimestamp = (stamp: string): Date =>
  new Date(
    Date.UTC(
      Number(stamp.slice(0, 4)),
      Number(stamp.slice(4, 6)) - 1,
      Number(stamp.slice(6, 8)),
      Number(stamp.slice(8, 10)),
      Number(stamp.slice(10, 12)),
      Number(stamp.slice(12, 14)),
    ),
  );

/** Migration names (file names without `.ts`) found in the directory, sorted. */
export const listMigrations = (dir: string = MIGRATIONS_DIR): string[] =>
  readdirSync(dir)
    .filter((file) => MIGRATION_FILE.test(file))
    .map((file) => file.slice(0, -'.ts'.length))
    .toSorted();

/**
 * Name for a new migration: the current UTC time, or one second after the
 * newest existing migration if that is later. The runner refuses a pending
 * migration that sorts before an applied one, so a new file must always sort
 * last, even with clock skew or two migrations created in the same second.
 */
export const newMigrationName = (
  description: string,
  existing: readonly string[],
  now: Date = new Date(),
): string => {
  const slug = toSnakeCase(description);
  if (!slug) {
    throw new Error('Describe the migration, e.g. "add exchange status"');
  }

  const latest = existing.at(-1);
  let timestamp = formatTimestamp(now);
  if (latest && timestamp <= latest.slice(0, 14)) {
    timestamp = formatTimestamp(new Date(parseTimestamp(latest).getTime() + 1000));
  }
  return `${timestamp}_${slug}`;
};

/**
 * The new file's contents. up() and down() throw until written, so a migration
 * committed unfinished fails the tests rather than silently doing nothing.
 */
export const renderMigration = (): string => `// import { sql } from 'drizzle-orm';
import type { MigrationDb } from '../migrator/types.js';

// DSQL rules for migrations:
// - One statement per db.execute(): each runs in its own transaction, and
//   DSQL allows only one DDL statement per transaction.
// - Make every statement idempotent (IF NOT EXISTS / IF EXISTS). A failure
//   part-way leaves earlier statements applied, and the next run starts the
//   migration again from the top.
// - Create indexes with CREATE INDEX ASYNC; the executor waits for the job.
// - down() must undo up(), in reverse order.
// - DDL cannot take bind parameters: use sql.identifier() for names, not a
//   plain \${value} (which becomes $1).
// - Identity columns and sequences need an explicit CACHE of 1 or >= 65536.
//
// e.g. await db.execute(sql\`ALTER TABLE exchanges ADD COLUMN IF NOT EXISTS ...\`);

export async function up(_db: MigrationDb): Promise<void> {
  throw new Error('Not implemented');
}

export async function down(_db: MigrationDb): Promise<void> {
  throw new Error('Not implemented');
}
`;

/** `"20261106000001_create_exchanges"` → `"createExchanges"`. */
const importName = (name: string): string =>
  name.slice(15).replace(/_([a-z0-9])/g, (_, char: string) => char.toUpperCase());

/** migrations/index.ts for the given migration names, which must be sorted. */
export const renderIndex = (names: readonly string[]): string => {
  const used = new Set<string>();
  const entries = names.map((name) => {
    let identifier = importName(name);
    if (/^\d/.test(identifier) || used.has(identifier)) {
      identifier = `migration${name.slice(0, 14)}`;
    }
    used.add(identifier);
    return { name, identifier };
  });

  const imports = entries
    .map((e) => `import * as ${e.identifier} from './${e.name}.js';\n`)
    .join('');
  const list =
    entries.length === 0
      ? '[]'
      : `[\n${entries.map((e) => `  { name: '${e.name}', ...${e.identifier} },\n`).join('')}]`;

  return `import type { Migration } from '../migrator/types.js';
${imports}
/**
 * Every migration, in the order it applies. The Lambda bundle can't scan this
 * directory at runtime, so new files must be added here; migrations.test.ts
 * fails if this list and the directory disagree.
 *
 * Generated by \`pnpm migration:create\`, which rewrites this file.
 */
export const migrations: readonly Migration[] = ${list};
`;
};

/** Writes the migration file and regenerates index.ts. Returns the new file's path. */
export const createMigration = (
  description: string,
  dir: string = MIGRATIONS_DIR,
  now: Date = new Date(),
): string => {
  const existing = listMigrations(dir);
  const name = newMigrationName(description, existing, now);
  const file = path.join(dir, `${name}.ts`);

  writeFileSync(file, renderMigration(), { flag: 'wx' });
  writeFileSync(path.join(dir, 'index.ts'), renderIndex([...existing, name]));
  return file;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const logger = new Logger({ serviceName: 'migration-create' });
  try {
    const file = createMigration(process.argv.slice(2).join(' '));
    logger.info(`Created ${path.relative(process.cwd(), file)}`);
    logger.info('Registered it in src/db/migrations/index.ts. Fill in up() and down().');
  } catch (error) {
    logger.error('Failed to create migration', { error });
    process.exitCode = 1;
  }
}
